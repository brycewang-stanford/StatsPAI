"""``fuzzydid`` -> ``sp.fuzzy_did`` translation, executed against Stata.

The reference numbers are the Stata 18 ``fuzzydid`` runs frozen in
``tests/reference_parity/_fixtures/fuzzydid_Stata.json`` (generated by
``_generate_fuzzydid_Stata.do``); the do-file lines are translated and run
with ``sp.stata`` on the same CSVs.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
import pytest

import statspai as sp
from statspai.exceptions import MethodIncompatibility

FX = Path(__file__).resolve().parent / "reference_parity" / "_fixtures"
REF = json.loads((FX / "fuzzydid_Stata.json").read_text(encoding="utf-8"))


def _point(res):
    return dict(zip(res.detail["estimator"], res.detail["estimate"]))


@pytest.mark.parametrize(
    "csv, line, key, rel",
    [
        ("fuzzydid_2x2.csv", "fuzzydid y g t d, did tc cic nose", "2x2_base", None),
        (
            "fuzzydid_2x2.csv",
            "fuzzydid y g t d, did tc cic nose numerator",
            "2x2_numerator",
            None,
        ),
        (
            "fuzzydid_2x2.csv",
            "fuzzydid y g t d, did tc nose continuous(x1) qualitative(x2)",
            "2x2_x1_x2",
            None,
        ),
        (
            "fuzzydid_2x2.csv",
            "fuzzydid y g t d, did tc nose continuous(x1) modelx(ols probit)",
            "2x2_x1_ols_probit",
            1e-6,  # Stata's probit stopping rule, see the parity test
        ),
        (
            "fuzzydid_ordered.csv",
            "fuzzydid y g t d, did tc cic nose newcateg(1 3)",
            "ordered_newcateg_1_3",
            None,
        ),
        (
            "fuzzydid_multi.csv",
            "fuzzydid y gt gf t d, did tc cic nose newcateg(0 2)",
            "multi_newcateg_0_2",
            None,
        ),
        (
            "fuzzydid_multi.csv",
            "fuzzydid y gt gf t d, did tc nose continuous(x1)",
            "multi_x1",
            None,
        ),
    ],
)
def test_translated_command_reproduces_stata(csv, line, key, rel):
    df = pd.read_csv(FX / csv)
    out = sp.from_stata(line)
    assert out["ok"] and out["complete"], out
    assert out["tool"] == "fuzzy_did"
    res = sp.stata(line, data=df)
    got = _point(res)
    assert set(got) == set(REF[key])
    for k, v in REF[key].items():
        if rel is None:
            assert got[k] == pytest.approx(v, abs=1e-11), k
        else:
            assert got[k] == pytest.approx(v, rel=rel), k


def test_bootstrap_options_map_to_the_call():
    out = sp.from_stata("fuzzydid y g t d, did tc cic breps(200) cluster(cl) eqtest")
    assert out["arguments"] == {
        "y": "y",
        "group_change": "g",
        "time": "t",
        "treat": "d",
        "estimators": ["did", "tc", "cic"],
        "se_method": "bootstrap",
        "n_boot": 200,
        "cluster": "cl",
        "eqtest": True,
        "cic_quantile": "stata",
    }
    # the command's default breps is 50
    assert sp.from_stata("fuzzydid y g t d, did")["arguments"]["n_boot"] == 50


def test_bootstrap_run_is_a_screen_against_stata():
    df = pd.read_csv(FX / "fuzzydid_2x2.csv")
    res = sp.stata("fuzzydid y g t d, did tc cic breps(500)", data=df)
    se = dict(zip(res.detail["estimator"], res.detail["se"]))
    # independent bootstrap draws (500 each): ~4.5% SD of the ratio, 15% screen
    for k, v in REF["2x2_boot_se"].items():
        assert se[k] == pytest.approx(v, rel=0.15), k


@pytest.mark.parametrize("option", ["lqte", "partial", "sieves", "sieveorder(3)"])
def test_unimplemented_options_are_refused(option):
    out = sp.from_stata(f"fuzzydid y g t d, did {option}")
    assert not out["ok"]
    assert "not translated" in out["error"]


def test_missing_estimator_and_bad_varlist_are_refused():
    assert not sp.from_stata("fuzzydid y g t d")["ok"]
    assert not sp.from_stata("fuzzydid y g d, did")["ok"]


def test_tagobs_is_reported_and_blocks_execution():
    out = sp.from_stata("fuzzydid y g t d, did tagobs")
    assert out["ok"] and not out["complete"]
    assert out["untranslated_options"] == ["tagobs"]
    df = pd.read_csv(FX / "fuzzydid_2x2.csv")
    with pytest.raises(MethodIncompatibility):
        sp.stata("fuzzydid y g t d, did tagobs", data=df)


def test_weights_are_refused():
    assert not sp.from_stata("fuzzydid y g t d [pw=w], did")["ok"]
