"""``sp.spatial_treatment`` against the method author's reference code.

Pollmann's spatialTreat-example (MIT licence; ``spatial_treat_estimator.R``
and ``sptreat_var.cpp`` at commit a73bca9) computes the ring estimator and
its design-based variance by enumerating every exposure of every unit.
StatsPAI uses closed forms for the same sums. Two designs (constant and
heterogeneous design probabilities, exposure radius equal to and below the
last ring edge) are generated by ``_fixtures/_generate_spatial_treatment_data.py``
and run through the R code by ``_fixtures/_generate_spatial_treatment_R.R``.

Every candidate location has a unit within reach in both designs, which is
where the author's per-ring normalisation of the own terms coincides with
Theorem 1's ``|S|``.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

import statspai as sp

HERE = Path(__file__).parent / "_fixtures"
REF = json.loads((HERE / "spatial_treatment_R.json").read_text(encoding="utf-8"))
UNITS = pd.read_csv(HERE / "spatial_treatment_units.csv")
LOCS = pd.read_csv(HERE / "spatial_treatment_locations.csv")
D0 = {1: 0.15, 2: 0.10}


@pytest.mark.parametrize("design", [1, 2])
def test_matches_author_reference_code(design):
    u = UNITS[UNITS.design == design].reset_index(drop=True)
    loc = LOCS[LOCS.design == design].reset_index(drop=True)
    res = sp.spatial_treatment(
        u,
        "Y",
        ["x", "y"],
        loc,
        treat="W",
        propensity="p",
        bins=[0, 0.05, 0.10, 0.15],
        max_effect_distance=D0[design],
        n_perm=0,
    )
    t = res.table
    ref = REF[f"d{design}"]
    S = len(loc)
    # 1e-9: both sides compute the same closed sums; the gap is the
    # %.17g CSV round trip and summation order (observed <= 1e-12).
    np.testing.assert_allclose(t.estimate, ref["tau"], rtol=1e-9)
    np.testing.assert_allclose(t.mu_treated, ref["mut"], rtol=1e-9)
    np.testing.assert_allclose(t.mu_control, ref["muc"], rtol=1e-9)
    np.testing.assert_allclose(t.se, ref["se"], rtol=1e-9)
    # The R code reports each component already divided by |S| twice.
    np.testing.assert_allclose(t.V_t / S, ref["Vt"], rtol=1e-9)
    np.testing.assert_allclose(t.V_c / S, ref["Vc"], rtol=1e-9)
    np.testing.assert_allclose(t.V_x / S, ref["Vx"], rtol=1e-9, atol=1e-12)
