"""Defects found by the Nov 2026 blind ML-causal replication probe.

Each test pins the number or the identity that exposed the defect.

* ``sp.dml_sensitivity(benchmark_covariates=)`` against ``doubleml`` 0.11.4
  ``sensitivity_benchmark`` on the Lalonde sample (fixture
  ``_fixtures/dml_benchmark_doubleml.json``, generated by
  ``_generate_dml_benchmark_doubleml.py`` from the CSV that
  ``_generate_dml_benchmark_data.py`` writes). Up to 1.43.1 the benchmark
  was a squared correlation of the covariate with residuals it had
  already been partialled out of: zero by construction.
* ``sp.dml(model='iivm')`` under one-sided non-compliance against
  ``DoubleMLIIVM(subgroups={'always_takers': False, ...})``: an interior
  clip of the first-stage probability moved an exact zero to 1e-4.
* ``sp.dml(model='irm', score='ATTE')`` labelled its estimate "ATE".
* ``sp.dose_response(method='dr')`` chose a bandwidth whose leave-one-out
  risk was NaN (``argmin`` returns the first NaN).
* The per-test-point weighted conformal quantile against its definition.

References
----------
[@chernozhukov2022long] [@chernozhukov2018double] [@kennedy2017parametric]
[@lei2021conformal]
"""

from __future__ import annotations

import json
import pathlib
import warnings

import numpy as np
import pandas as pd
import pytest
from sklearn.linear_model import LinearRegression, LogisticRegression

import statspai as sp
from statspai.exceptions import MethodIncompatibility

FIX = pathlib.Path(__file__).parent / "_fixtures"
X = ["age", "educ", "black", "hispanic", "married", "nodegree", "re74", "re75"]


def _logit() -> LogisticRegression:
    return LogisticRegression(C=np.inf, solver="newton-cholesky", max_iter=200)


@pytest.fixture(scope="module")
def data() -> pd.DataFrame:
    return pd.read_csv(FIX / "dml_benchmark_data.csv")


@pytest.fixture(scope="module")
def ref() -> dict:
    return json.loads((FIX / "dml_benchmark_doubleml.json").read_text(encoding="utf-8"))


def _fit(data: pd.DataFrame, model: str, **kw):
    learners = (
        dict(ml_g=LinearRegression(), ml_m=LinearRegression())
        if model == "plr"
        else dict(ml_g=LinearRegression(), ml_m=_logit())
    )
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        return sp.dml(
            data,
            y="re78",
            treat="treat",
            covariates=X,
            model=model,
            fold_indices="fold",
            **learners,
            **kw,
        )


@pytest.mark.parametrize("model", ["plr", "irm"])
def test_benchmark_covariates_match_doubleml(data, ref, model):
    """cf_y, cf_d, rho and delta_theta of each benchmark set.

    Same rows, folds and deterministic learners on both sides, so the
    tolerance is rounding only (observed 1e-13 relative; 1e-9 leaves room
    for another BLAS). ``rho`` is clipped to [-1, 1] by both packages.
    """
    fit = _fit(data, model)
    want = ref["benchmarks"][model]
    assert fit.estimate == pytest.approx(want["theta"], rel=1e-10)
    assert fit.se == pytest.approx(want["se"], rel=1e-10)
    sens = sp.dml_sensitivity(
        fit, benchmark_covariates=["re74", "black", ["re74", "re75"]]
    )
    table = sens.benchmarks.set_index("variable")
    assert list(table.index) == ["re74", "black", "re74+re75"]
    for name, row in want["sets"].items():
        got = table.loc[name]
        assert got["cf_y_bench"] == pytest.approx(row["cf_y"], rel=1e-9, abs=1e-12)
        assert got["cf_d_bench"] == pytest.approx(row["cf_d"], rel=1e-9, abs=1e-12)
        assert got["rho"] == pytest.approx(row["rho"], rel=1e-9, abs=1e-12)
        assert got["delta_theta"] == pytest.approx(row["delta_theta"], rel=1e-9)
        # the bound of the table is the paper's formula at the benchmark
        bound = np.sqrt(row["cf_y"] * row["cf_d"] / (1 - row["cf_d"])) * sens.s
        assert got["bias_bound"] == pytest.approx(bound, rel=1e-9, abs=1e-9)


def test_benchmark_multipliers_scale_the_strengths(data):
    fit = _fit(data, "plr")
    one = sp.dml_sensitivity(fit, benchmark_covariates=["re74"]).benchmarks.iloc[0]
    two = sp.dml_sensitivity(
        fit, benchmark_covariates=["re74"], k_y=2.0, k_d=3.0
    ).benchmarks.iloc[0]
    assert two["cf_y_bench"] == pytest.approx(2.0 * one["cf_y_bench"], rel=1e-12)
    assert two["cf_d_bench"] == pytest.approx(3.0 * one["cf_d_bench"], rel=1e-12)


def test_benchmark_with_repeated_and_clustered_fits(data):
    """The short fit reuses the long fit's seed, repetitions and clusters:
    benchmarking a covariate that is pure noise changes nothing, so every
    gain statistic is zero up to the noise covariate's own fit."""
    rng = np.random.default_rng(0)
    d = data.assign(noise=rng.normal(size=len(data)), g=np.arange(len(data)) % 60)
    for kw in (dict(n_rep=3, random_state=4), dict(cluster="g")):
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            fit = sp.dml(
                d,
                y="re78",
                treat="treat",
                covariates=X + ["noise"],
                model="plr",
                ml_g=LinearRegression(),
                ml_m=LinearRegression(),
                **kw,
            )
        row = sp.dml_sensitivity(fit, benchmark_covariates=["noise"]).benchmarks
        # an irrelevant regressor explains at most a share ~ 1/n of either
        # residual variance (n = 614): 0.02 is ten times that
        assert 0.0 <= row["cf_y_bench"].iloc[0] < 0.02
        assert 0.0 <= row["cf_d_bench"].iloc[0] < 0.02
        assert abs(row["delta_theta"].iloc[0]) < 0.1 * fit.se


def test_benchmark_refuses_what_it_cannot_do(data):
    fit = _fit(data, "plr")
    with pytest.raises(MethodIncompatibility, match="not_a_covariate"):
        sp.dml_sensitivity(fit, benchmark_covariates=["not_a_covariate"])
    with pytest.raises(MethodIncompatibility, match="no covariates"):
        sp.dml_sensitivity(fit, benchmark_covariates=[X])
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        weighted = sp.dml(
            data.assign(w=1.0 + data["black"]),
            y="re78",
            treat="treat",
            covariates=X,
            model="plr",
            ml_g=LinearRegression(),
            ml_m=LinearRegression(),
            sample_weight="w",
        )
    with pytest.raises(MethodIncompatibility, match="refit"):
        sp.dml_sensitivity(weighted, benchmark_covariates=["re74"])


def test_iivm_one_sided_noncompliance_matches_doubleml(data, ref):
    """Nobody with z = 0 is treated, so P(D = 1 | Z = 0, X) is exactly 0.

    1.43.1 clipped it to 1e-4 and was 2e-5 (relative) away from DoubleML on
    this fixture; the two now agree to rounding.
    """
    assert int(data.loc[data["z"] == 0, "dz"].sum()) == 0
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        fit = sp.dml(
            data,
            y="yz",
            treat="dz",
            instrument="z",
            covariates=X,
            model="iivm",
            ml_g=LinearRegression(),
            ml_m=_logit(),
            ml_r=_logit(),
            fold_indices="fold",
        )
    want = ref["iivm_onesided"]
    assert fit.estimate == pytest.approx(want["theta"], rel=1e-10)
    assert fit.se == pytest.approx(want["se"], rel=1e-10)
    assert fit.estimand == "LATE"


def test_irm_atte_is_labelled_att(data):
    att = _fit(data, "irm", score="ATTE")
    ate = _fit(data, "irm")
    assert att.estimand == "ATT"
    assert ate.estimand == "ATE"
    assert att.tidy()["term"].tolist() == ["ATT"]
    assert "ATT:" in att.summary()


def test_dml_seed_alias_and_option_hints(data):
    kw = dict(
        y="re78",
        treat="treat",
        covariates=X,
        ml_g=LinearRegression(),
        ml_m=LinearRegression(),
    )
    a = sp.dml(data, seed=11, **kw)
    b = sp.dml(data, random_state=11, **kw)
    assert a.estimate == b.estimate and a.se == b.se
    with pytest.raises(MethodIncompatibility, match="conflicting seeds"):
        sp.dml(data, seed=1, random_state=2, **kw)
    with pytest.raises(TypeError, match=r"'model_z' \(did you mean 'ml_r'\?\)"):
        sp.dml(data, model_z=LinearRegression(), **kw)
    with pytest.raises(TypeError, match=r"'n_fold' \(did you mean 'n_folds'\?\)"):
        sp.dml(data, n_fold=3, **kw)
    schema = {p["name"] for p in sp.describe_function("dml")["params"]}
    assert {"ml_g", "ml_m", "ml_r", "random_state", "alpha"} <= schema


def test_dr_dose_response_bandwidth_is_never_a_nan_risk():
    """One isolated dose makes the leave-one-out residual 0/0 at small
    bandwidths. The search must skip those and return the smallest finite
    risk; ``argmin`` over a grid holding NaN returned the NaN."""
    from statspai.dose_response.dr import loo_risk

    rng = np.random.default_rng(3)
    n = 300
    x = rng.normal(size=n)
    x[0] = 7.0  # one unit whose covariate puts its dose far from the rest
    t = np.round(20.0 + 10.0 * x + 10.0 * rng.normal(size=n))
    assert t[0] - np.sort(t)[-2] > 20.0
    y = 0.05 * t + x + rng.normal(size=n)
    df = pd.DataFrame({"y": y, "t": t, "x": x})
    xi = rng.normal(size=n)
    with warnings.catch_warnings():
        warnings.simplefilter("error", RuntimeWarning)
        # below the gap the isolated point is fitted by itself alone: no
        # leave-one-out prediction exists, and the risk is inf, never NaN
        direct = np.array([loo_risk(t, xi, h) for h in np.geomspace(0.5, 30, 60)])
        assert not np.isnan(direct).any()
        assert np.isinf(direct[0]) and np.isfinite(direct[-1])
        res = sp.dose_response(
            df,
            y="y",
            treat="t",
            covariates=["x"],
            method="dr",
            n_dose_points=5,
            treatment_model=LinearRegression(),
            outcome_model=LinearRegression(),
        )
    grid = np.asarray(res.model_info["bandwidth_risk"]["bandwidth"])
    risk = np.asarray(res.model_info["bandwidth_risk"]["risk"])
    assert not np.isnan(risk).any()
    finite = np.isfinite(risk)
    assert finite.any() and not finite.all()
    assert res.model_info["bandwidth"] == grid[finite][np.argmin(risk[finite])]


def test_weighted_conformal_quantile_equals_its_definition():
    """Each test point's quantile is the weighted quantile of the
    calibration residuals with the point's own weight placed on +inf."""
    from statspai.conformal_causal.counterfactual import (
        _test_point_quantiles,
        _weighted_quantile,
    )

    rng = np.random.default_rng(0)
    for trial in range(60):
        m, n_test = int(rng.integers(1, 40)), int(rng.integers(1, 25))
        resid = np.round(rng.exponential(size=m), int(rng.integers(0, 3)))
        w_cal = rng.choice([0.5, 1.0, 2.0, 1 / 3], size=m)
        w_test = rng.choice([0.0, 0.25, 1.0, 7.0, 1 / 3], size=n_test)
        level = float(rng.choice([0.9, 0.5, 0.95, 2 / 3, 1.0]))
        got = _test_point_quantiles(resid, w_cal, w_test, level)
        want = [
            _weighted_quantile(np.append(resid, np.inf), np.append(w_cal, wt), level)
            for wt in w_test
        ]
        assert np.array_equal(got, np.asarray(want))


def test_ips_names_the_fix_for_a_propensity_matrix():
    rng = np.random.default_rng(0)
    n = 50
    Xm = rng.normal(size=(n, 2))
    a = rng.integers(0, 2, size=n)
    r = rng.normal(size=n)
    pi_b = np.full((n, 2), 0.5)
    pi_e = np.column_stack([np.zeros(n), np.ones(n)])
    with pytest.raises(MethodIncompatibility, match="one propensity per row"):
        sp.ips(Xm, a, r, pi_e, pi_behavior=pi_b)
    by_row = sp.ips(Xm, a, r, pi_e, pi_behavior=pi_b[np.arange(n), a], clip=np.inf)
    # IPS with a known constant propensity is the scaled treated-arm sum
    assert by_row.value == pytest.approx(np.sum(r * (a == 1)) / (0.5 * n), rel=1e-12)


def test_conformal_summary_counts_unbounded_intervals():
    """With weak overlap some intervals are unbounded. The summary reports
    how many and averages the rest, where it used to print ``inf``."""
    from statspai.conformal_causal.counterfactual import _width_line

    assert _width_line(np.array([1.0, 3.0])) == "2.0000"
    line = _width_line(np.array([1.0, np.inf, 3.0, np.inf]))
    assert line.startswith("2.0000 over the bounded intervals")
    assert "2 of 4 unbounded" in line
    assert "all 2 intervals unbounded" in _width_line(np.array([np.inf, np.inf]))
