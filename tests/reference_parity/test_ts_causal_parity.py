def _stata(spec, imp, resp):
    rows = STATA[STATA.spec == spec]
    eq = rows.name.str.split(":").str[0]
    var = rows.name.str.split(".").str[-1].str.split(":").str[-1]
    return rows[(eq == imp) & (var == resp)]


