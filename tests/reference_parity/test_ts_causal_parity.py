def test_panel_twoways_on_unbalanced_panel_is_the_dummy_regression():
    df = pd.read_csv(FIX / "ts_causal_panel_unbal.csv")
    fit = sp.local_projections(
        df, outcome="y", shock="x", horizons=2, id="id", time="time",
        panel_effect="twoways", vce="ols",
    )  # fmt: skip
    # horizon 2 by brute force: y_{t+2} on x and unit + period dummies
    d = df.sort_values(["id", "time"]).copy()
    d["lead"] = d.groupby("id")["y"].shift(-2)
    d = d.dropna(subset=["lead"])
    X = np.column_stack(
        [
            d.x,
            pd.get_dummies(d.id, dtype=float),
            pd.get_dummies(d.time, dtype=float).iloc[:, 1:],
        ]
    )
    b, *_ = np.linalg.lstsq(X, d.lead.to_numpy(), rcond=None)
    e = d.lead.to_numpy() - X @ b
    s2 = e @ e / (len(e) - np.linalg.matrix_rank(X))
    se = np.sqrt(s2 * np.linalg.inv(X.T @ X)[0, 0])
    assert abs(fit.irf[2] - b[0]) < 1e-9 * abs(b[0])
    assert abs(fit.se[2] - se) < 1e-8 * se


