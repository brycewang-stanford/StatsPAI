# ---------------------------------------------- historical decomposition
def _chol_svar():
    v = pd.read_csv(FIX / "ts_causal_var.csv")
    fit = sp.var(v, variables=["i", "x", "p"], lags=2)
    return v, fit, sp.svar(fit, B=np.tril(np.full((3, 3), np.nan)))


def test_historical_decomposition_matches_svars():
    _, _, res = _chol_svar()
    hd = res.historical_decomposition()
    for k, name in enumerate(["i", "x", "p"]):
        ours = hd[hd.variable == name][["shock1", "shock2", "shock3"]].to_numpy()
        ref = np.array(R["svars_hd"][k])
        # scale-relative: accumulated sums pass near zero
        assert np.max(np.abs(ours - ref)) < 1e-12 * np.max(np.abs(ref))


def _shock_free_path(fit, lev):
    B, k, p = fit._B, fit._k, fit._lags
    base = lev.copy()
    for t in range(p, len(lev)):
        base[t] = sum(B[j * k : (j + 1) * k, :].T @ base[t - j - 1] for j in range(p))
        base[t] += B[k * p, :]
    return base[p:]


def test_historical_decomposition_baseline_is_the_shock_free_path():
    v, fit, res = _chol_svar()
    hd = res.historical_decomposition()
    got = hd.pivot(index="period", columns="variable", values="baseline")
    want = _shock_free_path(fit, v[["i", "x", "p"]].to_numpy())
    np.testing.assert_allclose(got[["i", "x", "p"]].to_numpy(), want, atol=1e-10)


def test_historical_decomposition_refuses_sign_restrictions():
    _, fit, _ = _chol_svar()
    res = sp.svar(fit, sign={"s": {"i": "+"}}, n_draws=5, seed=0)
    with pytest.raises(MethodIncompatibility, match="sign restrictions"):
        res.historical_decomposition()


# --------------------------------------------------------------- proxy SVAR
def _proxy_dgp(T, seed, strength=0.5):
    rng = np.random.default_rng(seed)
    H = np.array([[1.0, 0.3, 0.0], [0.5, 1.0, 0.2], [-0.4, 0.6, 1.0]])
    A1 = np.array([[0.5, 0.1, 0.0], [0.0, 0.4, 0.1], [0.1, 0.0, 0.3]])
    eps = rng.normal(size=(T, 3))
    y = np.zeros((T, 3))
    for t in range(1, T):
        y[t] = A1 @ y[t - 1] + H @ eps[t]
    m = strength * eps[:, 0] + rng.normal(size=T)
    return pd.DataFrame(y, columns=["i", "x", "p"]), m, H


def test_proxy_svar_is_two_stage_least_squares_on_residuals():
    df, m, _ = _proxy_dgp(400, 3)
    fit = sp.var(df, variables=["i", "x", "p"], lags=1)
    res = sp.svar(fit, proxy=m, proxy_target="i")
    u = fit.residuals.to_numpy()
    Z = np.column_stack([np.ones(len(u)), m[1:]])
    X = np.column_stack([np.ones(len(u)), u[:, 0]])
    PZX = Z @ np.linalg.solve(Z.T @ Z, Z.T @ X)
    for i in range(3):
        b = np.linalg.solve(PZX.T @ X, PZX.T @ u[:, i])[1]
        assert abs(res.impact.iloc[i, 0] - b) < 1e-12
    assert res.identification == "proxy"


def test_proxy_svar_recovers_the_impact_column():
    df, m, H = _proxy_dgp(20000, 11)
    fit = sp.var(df, variables=["i", "x", "p"], lags=1)
    unit = sp.svar(fit, proxy=m, proxy_target="i")
    std = sp.svar(fit, proxy=m, proxy_target="i", proxy_scale="std")
    # sampling sd of the ratios at T = 20000 is about 0.01
    np.testing.assert_allclose(unit.impact.iloc[:, 0], H[:, 0] / H[0, 0], atol=0.04)
    np.testing.assert_allclose(std.impact.iloc[:, 0], H[:, 0], atol=0.04)
    # the std-scaled column satisfies b' Sigma^{-1} b = 1
    b = std.impact.iloc[:, 0].to_numpy()
    sig = fit.sigma_u.to_numpy()
    assert abs(b @ np.linalg.solve(sig, b) - 1.0) < 1e-12
    # FEVD shares of one shock lie in [0, 1]
    fe = unit.fevd(8)
    assert fe.fevd.between(0, 1).all()


def test_proxy_svar_bootstrap_bands_and_weak_proxy_warning():
    df, m, _ = _proxy_dgp(300, 5)
    fit = sp.var(df, variables=["i", "x", "p"], lags=1)
    res = sp.svar(fit, proxy=m, proxy_target="i")
    band = res.irf(3, ci="bootstrap", reps=60, seed=2)
    assert (band.lower <= band.irf + 1e-12).all() and (
        band.irf <= band.upper + 1e-12
    ).all()
    impact_i = band[(band.response == "i") & (band.period == 0)]
    assert float(impact_i.se.iloc[0]) < 1e-12  # normalised impact is fixed at 1
    _, weak, _ = _proxy_dgp(300, 5, strength=0.02)
    with warnings.catch_warnings(record=True) as rec:
        warnings.simplefilter("always")
        r = sp.svar(fit, proxy=weak, proxy_target="i")
    assert r.proxy_diagnostics["weak"]
    assert any(issubclass(w.category, AssumptionWarning) for w in rec)


def _iv_hc0_se(fit, m, j):
    """HC0 standard error of the 2SLS impact ratio of variable ``j`` (the
    proxy instruments the target residual, column 0, with a constant)."""
    u = fit.residuals.to_numpy()
    mm = m[1:] - m[1:].mean()
    ui = u[:, 0] - u[:, 0].mean()
    uj = u[:, j] - u[:, j].mean()
    b = np.sum(uj * mm) / np.sum(ui * mm)
    e = uj - b * ui
    return float(np.sqrt(np.sum(e**2 * mm**2)) / abs(np.sum(ui * mm)))


@pytest.mark.parametrize("seed", [5, 6])
def test_proxy_svar_bootstrap_se_matches_robust_iv_se(seed):
    # The impact ratio is a just-identified 2SLS coefficient on the
    # residuals, so its bootstrap SE should match the HC0 2SLS SE. The
    # Rademacher wild bootstrap of the residual and the proxy (used before
    # 2026-10-20) gave about a ninth of it: the common sign cancels in
    # u_t m_t, so the identifying covariance never moved.
    df, m, _ = _proxy_dgp(300, seed)
    fit = sp.var(df, variables=["i", "x", "p"], lags=1)
    res = sp.svar(fit, proxy=m, proxy_target="i")
    assert res.proxy_diagnostics["block_length"] == 7  # ceil(299 ** (1/3))
    band = res.irf(0, ci="bootstrap", reps=400, seed=1)
    for j, v in [(1, "x"), (2, "p")]:
        se = float(band[(band.response == v) & (band.period == 0)].se.iloc[0])
        assert 0.8 < se / _iv_hc0_se(fit, m, j) < 1.25


def test_proxy_svar_bootstrap_coverage_screen():
    # 50 simulated samples, nominal 95% bands for the impact responses of
    # x and p (true 0.5 and -0.4). The wild bootstrap covered about 18%.
    hits = np.zeros(2)
    n = 50
    for r in range(n):
        df, m, H = _proxy_dgp(300, 1000 + r)
        fit = sp.var(df, variables=["i", "x", "p"], lags=1)
        band = sp.svar(fit, proxy=m, proxy_target="i").irf(
            0, ci="bootstrap", reps=99, seed=r
        )
        for j, v in enumerate(["x", "p"]):
            row = band[(band.response == v) & (band.period == 0)].iloc[0]
            hits[j] += row.lower <= H[j + 1, 0] / H[0, 0] <= row.upper
    assert (hits / n >= 0.8).all(), hits / n


def test_proxy_svar_block_length_is_validated():
    df, m, _ = _proxy_dgp(120, 3)
    fit = sp.var(df, variables=["i", "x", "p"], lags=1)
