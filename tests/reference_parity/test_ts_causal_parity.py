"""IV, state-dependent and panel local projections; proxy SVAR; historical
decomposition; Dumitrescu-Hurlin panel Granger test.

References (fixtures regenerated by ``_fixtures/_generate_ts_causal_*``):

* R ``lpirfs`` 0.2.5 (``lp_lin_iv``, ``lp_nl_iv``, ``lp_nl``,
  ``lp_lin_panel``) and ``plm`` 2.6 (``pgrangertest``) -- GPL packages used
  only as black boxes, through their documented interfaces and outputs;
* R ``svars`` 1.3 (``hd``);
* Stata 18 ``lpirf`` (dynamic multipliers of ``exog()``) and ``xtgcause``
  (SSC).

Every row agrees to 1e-9 relative or better (most to 1e-14; the
Hodrick-Prescott state to 1e-11, a dense inverse in lpirfs against a sparse
solve here). The proxy SVAR has no reference implementation available; its
evidence is the two-stage least squares identity, recovery of the true
impact column on a long simulated sample, and for its bootstrap bands the
heteroskedasticity-robust 2SLS standard error and a coverage screen.
"""

