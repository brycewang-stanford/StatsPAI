def _rel(a, b):
    a = np.asarray(a, dtype=float)
    b = np.asarray(b, dtype=float)
    keep = np.abs(b) > 1e-12
    return float(np.max(np.abs(a[keep] - b[keep]) / np.abs(b[keep])))


