"""The recomputed Hansen (1997) sup-F response surface against the paper.

``src/statspai/timeseries/_hansen_supf_table.py`` is generated by
``scripts/generate_hansen_supf_table.py`` (simulation of the sup-F
distribution as Hansen describes it, seed in the script). The paper prints
the coefficients for five pi_0 and selected m to two decimals (Table 2,
p. 64); the generator carries those entries. A printed entry stands for a
box of coefficients (half a unit in the last printed digit), so the check
is: our p-value at the statistic values that give p = .5, ..., .001 under
the printed coefficients lies within the range the box spans, widened by
twice the maximum absolute error Hansen reports for his approximation
(Table 1: 0.0058), since both tables are independent approximations of the
same function.
"""

from __future__ import annotations

import importlib.util
import itertools
import sys
from pathlib import Path

import numpy as np
import pytest
from scipy import stats

from statspai.exceptions import MethodIncompatibility
from statspai.timeseries._hansen_supf_table import HANSEN_SUP_BETA

ROOT = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location(
    "_gen_hansen", ROOT / "scripts" / "generate_hansen_supf_table.py"
)
GEN = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(GEN)
TWICE_HANSEN_MAX_ERROR = 2 * 0.0058
_sb = sys.modules.get("statspai.timeseries.structural_break")
if _sb is None:  # pragma: no cover - imported by statspai already
    import statspai.timeseries.structural_break  # noqa: F401

    _sb = sys.modules["statspai.timeseries.structural_break"]
hansen_supf_pvalue = _sb.hansen_supf_pvalue


def test_table_shape():
    assert sorted(HANSEN_SUP_BETA) == list(range(1, 41))
    assert all(
        len(rows) == 25 and all(len(r) == 3 for r in rows)
        for rows in HANSEN_SUP_BETA.values()
    )


@pytest.mark.parametrize(
    "pi0,m",
    [(pi0, m) for pi0, rows in GEN.TABLE2.items() for m in rows],
)
def test_matches_the_coefficients_printed_in_table_2(pi0, m):
    a0, a1, eta = GEN.TABLE2[pi0][m]
    i = int(np.flatnonzero(np.isclose(GEN.PI0, pi0))[0])
    b0, b1, e = HANSEN_SUP_BETA[m][i]
    x = (stats.chi2.isf(np.array([0.5, 0.2, 0.1, 0.05, 0.01, 0.001]), eta) - a0) / a1
    box = [
        stats.chi2.sf(c0 + c1 * x, ce)
        for c0, c1, ce in itertools.product(
            (a0 - 0.005, a0 + 0.005), (a1 - 0.005, a1 + 0.005), (eta - 0.05, eta + 0.05)
        )
    ]
    lo, hi = np.min(box, axis=0), np.max(box, axis=0)
    ours = stats.chi2.sf(b0 + b1 * x, e)
    gap = np.maximum(lo - ours, ours - hi)
    assert np.all(gap <= TWICE_HANSEN_MAX_ERROR), (pi0, m, gap)


def test_pvalue_uses_the_table_row_at_a_node():
    t0, t1, eta = HANSEN_SUP_BETA[7][GEN.PI0.tolist().index(0.15)]
    assert hansen_supf_pvalue(12.5, 7, 0.15) == pytest.approx(
        stats.chi2.sf(t0 + t1 * 12.5, eta), rel=1e-14
    )


@pytest.mark.parametrize("k", [0, 41, 2.5])
def test_k_outside_the_table_is_refused(k):
    with pytest.raises(MethodIncompatibility, match="1 <= k <= 40"):
        hansen_supf_pvalue(9.0, k, 0.15)


@pytest.mark.parametrize("lam", [0.0, 0.6, -1.0])
def test_trimming_that_is_neither_pi0_nor_lambda_is_refused(lam):
    # 0.5 < pi_0 < 1 used to extrapolate to a negative p-value.
    with pytest.raises(MethodIncompatibility, match="neither a pi_0"):
        hansen_supf_pvalue(9.0, 2, lam)
