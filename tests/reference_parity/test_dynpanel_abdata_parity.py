# ---------------------------------------------------------------------------
# G. Blundell-Bond system GMM against xtabond2.
#
#    xtabond2 is the reference the applied literature reports, so it is the
#    anchor for the whole level-equation layout: which lagged difference
#    instruments the level equation (only the most recent one — deeper lags
#    are redundant given the transformed-equation moments), that iv() enters
#    as a *single* column spanning both equations, that _cons is both a
#    regressor and its own level instrument, and Roodman's h(3) weight
#    H = [[MM', M], [M', I]].
# ---------------------------------------------------------------------------


class TestSystemGMM:
    def test_system_onestep_matches_xtabond2(self, abdata, stata):
        spec = "D4_x2_sys_1step"
        r = _fit(abdata, x=["w", "k"], lags=1, method="system")
        _assert_matches(r, stata[spec], spec)
        _assert_sample(r, stata[spec], spec, instrument_key="j")
        assert r.model_info["n_instruments"] == 38

    def test_system_twostep_windmeijer_matches_xtabond2(self, abdata, stata):
        spec = "D5_x2_sys_2step_wc"
        r = _fit(abdata, x=["w", "k"], lags=1, method="system", twostep=True)
        _assert_matches(r, stata[spec], spec)
        _assert_sample(r, stata[spec], spec, instrument_key="j")

    def test_system_collapsed_matches_xtabond2(self, abdata, stata):
        spec = "D6_x2_sys_collapse"
        r = _fit(
            abdata, x=["w", "k"], lags=1, method="system", twostep=True, collapse=True
        )
        _assert_matches(r, stata[spec], spec)
        _assert_sample(r, stata[spec], spec, instrument_key="j")
        assert r.model_info["n_instruments"] == 11

    def test_system_ar1_matches_xtabond2(self, abdata, stata):
        """The AR test stays a statement about the *differenced* errors.

        Under system GMM only the transformed rows supply residual pairs;
        getting this wrong (letting level rows in) shifts the statistic
        visibly, so matching xtabond2's -2.218 is a real check.
        """
        r = _fit(abdata, x=["w", "k"], lags=1, method="system")
        np.testing.assert_allclose(
            r.model_info["ar1_z"],
            stata["D4_x2_sys_1step"]["e"]["ar1"],
            rtol=1e-7,
            err_msg="system-GMM AR(1) z differs from xtabond2.",
        )

    def test_system_adds_the_level_equation_and_its_moments(self, abdata):
        """Structural check on what stacking the level equation changes.

        Relative to the same difference-GMM fit, system GMM must (a) add
        level rows (891 of them on abdata, one per unit-period with ``n``
        and ``L.n``), (b) add level moments — the 7 lagged-difference
        instruments plus the ``_cons`` column — and (c) report an intercept
        the differenced equation cannot identify. Anything less means the
        level equation was not really stacked.
        """
        diff = _fit(abdata, x=["w", "k"], lags=1)
        system = _fit(abdata, x=["w", "k"], lags=1, method="system")
        assert diff.model_info["n_obs_level"] == 0
        assert system.model_info["n_obs_level"] == 891
        assert system.model_info["n_obs_diff"] == diff.model_info["n_obs_diff"]
        assert system.model_info["n_instruments"] == (
            diff.model_info["n_instruments"] + 8
        )
        assert "_cons" not in list(diff.detail["variable"])
        assert list(system.detail["variable"])[-1] == "_cons"

    def test_xtdpdsys_alias_equals_method_system(self, abdata):
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            a = sp.xtdpdsys(abdata, y="n", x=["w", "k"], id="id", time="year")
        b = _fit(abdata, x=["w", "k"], lags=1, method="system")
        np.testing.assert_allclose(
            a.detail["coefficient"].to_numpy(float),
            b.detail["coefficient"].to_numpy(float),
            rtol=1e-14,
        )

    def test_hansen_j_matches_xtabond2_in_every_configuration(self, abdata, stata):
        """The Hansen J has no free scale, so it must match exactly.

        (The Sargan statistic does have one — see
        ``test_sargan_convention_differs_from_xtabond2`` — which is why the
        J is the cross-package anchor.)
        """
        cases = [
            ("D1_x2_diff_1step", dict(lags=1)),
            ("D2_x2_diff_collapse", dict(lags=1, collapse=True)),
            ("D3_x2_diff_ivwk", dict(x=["w", "k"], lags=1)),
            ("D4_x2_sys_1step", dict(x=["w", "k"], lags=1, method="system")),
            (
                "D6_x2_sys_collapse",
                dict(
                    x=["w", "k"],
                    lags=1,
                    method="system",
                    twostep=True,
                    collapse=True,
                ),
            ),
        ]
        for spec, kwargs in cases:
            r = _fit(abdata, **kwargs)
            np.testing.assert_allclose(
                r.model_info["hansen_stat"],
                stata[spec]["e"]["hansen"],
                rtol=1e-9,
                err_msg=f"[{spec}] Hansen J differs from xtabond2.",
            )
            assert r.model_info["hansen_df"] == int(stata[spec]["e"]["hansen_df"])

    def test_sargan_convention_differs_from_xtabond2_by_a_known_factor(
        self, abdata, stata
    ):
        """Pin the documented scale difference instead of hiding it.

        StatsPAI follows ``xtabond``: ``sigma2 = e*'e* / (2 (N* - k))`` over
        the transformed rows. ``xtabond2`` divides by ``2 N*``. The ratio is
        therefore exactly ``N* / (N* - k)`` — asserting it proves the two are
        the same statistic under two finite-sample conventions, not two
        different statistics.
        """
        for spec, kwargs in (
            ("D1_x2_diff_1step", dict(lags=1)),
            ("D3_x2_diff_ivwk", dict(x=["w", "k"], lags=1)),
            ("D4_x2_sys_1step", dict(x=["w", "k"], lags=1, method="system")),
        ):
            r = _fit(abdata, **kwargs)
            n_star = r.model_info["n_obs_diff"]
            k = r.model_info["n_regressors"]
            np.testing.assert_allclose(
                r.model_info["sargan_stat"] * n_star / (n_star - k),
                stata[spec]["e"]["sargan"],
                rtol=1e-9,
                err_msg=(
                    f"[{spec}] the Sargan statistic no longer differs from "
                    "xtabond2 by exactly N*/(N*-k) — a convention drifted."
                ),
            )


# ---------------------------------------------------------------------------
# H. Forward orthogonal deviations (Arellano-Bover) against
#    ``xtabond2, orthogonal``.
#
#    Two conventions had to be got right and both are observable on this
#    ragged panel:
#      * the transformed row is *labelled* with the period of the first
#        difference it replaces, so the instrument grid, the level-equation
#        cross block and the AR test share one period index;
#      * the a-priori error covariance H is built from the **balanced-grid**
#        FOD operator ("H always has block diagonal form, with all blocks
#        the same" -- xtabond2 help), not from each unit's own operator.
#        Using the per-unit one moves the system-GMM coefficients by up to
#        13% here.
# ---------------------------------------------------------------------------


class TestForwardOrthogonalDeviations:
    def test_fod_difference_onestep(self, abdata, stata):
        spec = "D7_x2_fod_diff"
        r = _fit(abdata, x=["w", "k"], lags=1, orthogonal=True)
        _assert_matches(r, stata[spec], spec)
        _assert_sample(r, stata[spec], spec, instrument_key="j")

    def test_fod_difference_twostep(self, abdata, stata):
        spec = "D10_x2_fod_diff_2step"
        r = _fit(abdata, x=["w", "k"], lags=1, orthogonal=True, twostep=True)
        _assert_matches(r, stata[spec], spec)
        _assert_sample(r, stata[spec], spec, instrument_key="j")

    def test_fod_system_onestep(self, abdata, stata):
        spec = "D9_x2_fod_sys_1step"
        r = _fit(abdata, x=["w", "k"], lags=1, method="system", orthogonal=True)
        _assert_matches(r, stata[spec], spec)
        _assert_sample(r, stata[spec], spec, instrument_key="j")

    def test_fod_system_twostep(self, abdata, stata):
        spec = "D8_x2_fod_sys_2step"
        r = _fit(
            abdata,
            x=["w", "k"],
            lags=1,
            method="system",
            orthogonal=True,
            twostep=True,
        )
        _assert_matches(r, stata[spec], spec)
        _assert_sample(r, stata[spec], spec, instrument_key="j")

    def test_fod_operator_is_orthonormal(self):
        """``M M' = I`` — the property the whole transform exists for.

        It is what makes the transformed errors serially uncorrelated, so
        the one-step weight needs no MA(1) correction. If this breaks, the
        parity above would still pass on abdata but every other panel would
        be silently mis-weighted.
        """
        from statspai.gmm._dynpanel._moments import fod_operator

        for T in (2, 3, 5, 9, 20):
            M = fod_operator(T)
            assert M.shape == (T - 1, T)
            np.testing.assert_allclose(
                M @ M.T, np.eye(T - 1), atol=1e-12, err_msg=f"M M' != I at T={T}"
            )

    def test_fod_beats_first_differences_on_a_gappy_panel(self, abdata):
        """FOD's practical selling point: a gap costs one row, not two.

        Punching an interior hole in every third firm destroys the first
        differences on *both* sides of it, but only one forward deviation.
        The transformed sample must therefore shrink strictly less under
        ``orthogonal=True``.
        """
        holed = abdata[
            ~((abdata["id"] % 3 == 0) & (abdata["year"] == 1980))
        ].reset_index(drop=True)
        fd = _fit(holed, x=["w", "k"], lags=1)
        fod = _fit(holed, x=["w", "k"], lags=1, orthogonal=True)
        full_fd = _fit(abdata, x=["w", "k"], lags=1)
        lost_fd = full_fd.model_info["n_obs_diff"] - fd.model_info["n_obs_diff"]
        lost_fod = (
            _fit(abdata, x=["w", "k"], lags=1, orthogonal=True).model_info["n_obs_diff"]
            - fod.model_info["n_obs_diff"]
        )
        assert lost_fod < lost_fd, (
            f"forward orthogonal deviations lost {lost_fod} rows to the gaps "
            f"and first differencing lost {lost_fd}: FOD is supposed to lose "
            "strictly fewer."
        )


