"""Reference parity: dynamic-panel GMM against Stata 18 on ``abdata``.

Dataset
-------
``_fixtures/dynpanel_abdata.csv`` is Stata's ``webuse abdata`` — the
Arellano & Bond (1991) panel of 140 UK firms, 1976-1984, unbalanced and
ragged (7-9 observations per firm).  It is exported in ``%21.16e`` so
Python estimates on *the same bytes* Stata did; nothing is re-simulated,
so a mismatch is a genuine numerical disagreement and not a DGP artefact.

Reference
---------
``_fixtures/dynpanel_stata.json``, generated by
``_fixtures/_generate_dynpanel_stata.do`` (Stata 18 MP, plus ``xtabond2``
from SSC) and folded by ``_fixtures/_fold_dynpanel_stata.py``.  Each spec
carries the full coefficient vector, its standard errors, and the
``e()`` scalars (``N``, ``zrank``/``j``, ``arm1``, ``arm2``, ``sargan``).

Why this file exists
--------------------
``sp.xtabond``'s only prior numeric guarantee was a self-consistency check
against ``sp.gmm`` plus a Monte-Carlo recovery band.  Neither would have
caught the defect this suite was written to lock out: because the
estimator applied a listwise ``dropna`` across ``[id, time, y] + x``
*before* building anything, a lagged covariate's leading ``NaN``s deleted
the corresponding ``y`` levels from the **instrument** pool.  Reproducing
the Arellano-Bond (1991) Table 4 specification therefore used 19 of 32
instruments and 331 of 611 observations, and returned rho = 0.660 where
Stata returns 0.849 — a 22% error that no recovery band would flag.

Tolerance
---------
``rtol = 1e-9``.  These are the same closed-form linear-algebra
operations on the same doubles, so agreement is limited only by BLAS
reassociation; probed worst case across all specs below is ~1e-10 on a
coefficient whose value is 5e-4 (the ``yr1984`` dummy), and ~3e-12
elsewhere.  Anything looser would let a real convention change hide.

References
----------
Arellano, M. and Bond, S. (1991). *Review of Economic Studies* 58(2),
277-297. [@arellano1991some]
Roodman, D. (2009). How to do xtabond2. *Stata Journal* 9(1), 86-136.
[@roodman2009xtabond]
Windmeijer, F. (2005). *Journal of Econometrics* 126(1), 25-51.
[@windmeijer2005finite]
"""

from __future__ import annotations

import json
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

import statspai as sp
from statspai.exceptions import IdentificationFailure

FIXTURES = Path(__file__).parent / "_fixtures"
DATA_CSV = FIXTURES / "dynpanel_abdata.csv"
STATA_JSON = FIXTURES / "dynpanel_stata.json"
R_JSON = FIXTURES / "dynpanel_R.json"

RTOL = 1e-9

# StatsPAI labels lagged terms "L1.x"; Stata prints the first lag as "L.x".
_NAME_MAP = {"L1.n": "L.n", "L1.w": "L.w", "L1.k": "L.k"}

pytestmark = pytest.mark.skipif(
    not (DATA_CSV.exists() and STATA_JSON.exists()),
    reason="dynamic-panel Stata fixture not generated",
)


@pytest.fixture(scope="module")
def abdata() -> pd.DataFrame:
    return pd.read_csv(DATA_CSV)


@pytest.fixture(scope="module")
def stata() -> dict:
    return json.loads(STATA_JSON.read_text(encoding="utf-8"))


def _fit(abdata, **kwargs):
    with warnings.catch_warnings():
        # Instrument-count and gap advisories are diagnostics, not the
        # subject of these tests.
        warnings.simplefilter("ignore")
        return sp.xtabond(abdata, y="n", id="id", time="year", **kwargs)


def _assert_matches(result, ref: dict, spec: str) -> None:
    """Every coefficient and SE StatsPAI reports must match Stata's."""
    got_names = list(result.detail["variable"])
    matched = 0
    for i, name in enumerate(got_names):
        key = _NAME_MAP.get(name, name)
        assert key in ref["coef"], (
            f"[{spec}] StatsPAI reports a term {name!r} that Stata does not "
            f"({sorted(ref['coef'])}); the two designs differ."
        )
        np.testing.assert_allclose(
            float(result.detail["coefficient"].iloc[i]),
            ref["coef"][key],
            rtol=RTOL,
            atol=1e-12,
            err_msg=f"[{spec}] coefficient on {name} differs from Stata.",
        )
        np.testing.assert_allclose(
            float(result.detail["se"].iloc[i]),
            ref["se"][key],
            rtol=RTOL,
            atol=1e-12,
            err_msg=f"[{spec}] standard error on {name} differs from Stata.",
        )
        matched += 1
    assert matched == len(ref["coef"]), (
        f"[{spec}] Stata reports {len(ref['coef'])} terms but StatsPAI "
        f"reports {matched}: {got_names}."
    )


def _assert_sample(result, ref: dict, spec: str, instrument_key: str = "zrank") -> None:
    e = ref["e"]
    assert result.model_info["n_obs"] == int(e["N"]), (
        f"[{spec}] differenced sample size {result.model_info['n_obs']} != "
        f"Stata's e(N) {int(e['N'])} — the row-inclusion rule differs."
    )
    if instrument_key in e:
        assert result.model_info["n_instruments"] == int(e[instrument_key]), (
            f"[{spec}] instrument count {result.model_info['n_instruments']} "
            f"!= Stata's e({instrument_key}) {int(e[instrument_key])}."
        )


