    def test_ab1991_twostep_windmeijer(self, abdata, stata):
        spec = "B2_ab1991_2step_wc"
        r = _fit(abdata, x=["l(0/1).w", "l(0/2).k"], lags=2, twostep=True)
        _assert_matches(r, stata[spec], spec)
        _assert_sample(r, stata[spec], spec)

    def test_ab1991_with_year_dummies(self, abdata, stata):
        spec = "B3_ab1991_yeardum"
        yrs = [f"yr{t}" for t in range(1979, 1985)]
        r = _fit(abdata, x=["l(0/1).w", "l(0/2).k"] + yrs, lags=2)
        _assert_matches(r, stata[spec], spec)
        _assert_sample(r, stata[spec], spec)

    def test_lag_operator_equals_manual_lags(self, abdata):
        """``l(0/2).k`` must equal hand-built lag columns — now that the
        estimator no longer deletes rows on a covariate's leading NaNs."""
        manual = abdata.sort_values(["id", "year"]).copy()
        for lag in (1, 2):
            manual[f"k_L{lag}"] = manual.groupby("id")["k"].shift(lag)
            manual[f"w_L{lag}"] = manual.groupby("id")["w"].shift(lag)
        a = _fit(abdata, x=["l(0/1).w", "l(0/2).k"], lags=2)
        b = _fit(manual, x=["w", "w_L1", "k", "k_L1", "k_L2"], lags=2)
        np.testing.assert_allclose(
            b.detail["coefficient"].to_numpy(float),
            a.detail["coefficient"].to_numpy(float),
            rtol=1e-10,
            err_msg=(
                "hand-built lag columns disagree with the lag operator — the "
                "listwise-deletion regression is back."
            ),
        )
        assert a.model_info["n_obs"] == b.model_info["n_obs"] == 611
        assert a.model_info["n_instruments"] == b.model_info["n_instruments"] == 32


