class TestInstrumentWindow:
    def test_capped_depth_matches_maxldep(self, abdata, stata):
        """``gmm_lags=(2, 4)`` == Stata ``xtabond ..., maxldep(3)``."""
        spec = "A6_ar1_maxldep3"
        r = _fit(abdata, lags=1, gmm_lags=(2, 4))
        _assert_matches(r, stata[spec], spec)
        _assert_sample(r, stata[spec], spec)

    def test_deeper_minimum_lag(self, abdata, stata):
        """``gmm_lags=(3, None)`` == ``xtabond2 ... gmm(L.n, lag(2 .))``."""
        spec = "A7_minlag3"
        r = _fit(abdata, lags=1, gmm_lags=(3, None))
        _assert_matches(r, stata[spec], spec)
        _assert_sample(r, stata[spec], spec, instrument_key="j")

    def test_collapse_matches_xtabond2(self, abdata, stata):
        """``collapse=True`` == ``xtabond2 ..., gmm(..., collapse)``.

        The whole point of collapsing is that it changes the answer: on
        abdata it moves rho from 1.02 to 1.39 and cuts 28 instruments to 7.
        Matching Stata here is therefore a real test of the collapsed
        moment layout, not of a no-op flag.
        """
        spec = "D2_x2_diff_collapse"
        r = _fit(abdata, lags=1, collapse=True)
        _assert_matches(r, stata[spec], spec)
        _assert_sample(r, stata[spec], spec, instrument_key="j")
        assert r.model_info["n_instruments"] == 7
        assert r.model_info["collapse"] is True


