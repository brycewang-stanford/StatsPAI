class TestInstrumentClasses:
    def test_predetermined_matches_stata_pre(self, abdata, stata):
        """``pre(w, lagstruct(1, .))`` == ``predetermined_lags=(2, None)``."""
        spec = "C1_w_predetermined"
        r = _fit(
            abdata,
            x=["l(0/2).k"],
            predetermined=["l(0/1).w"],
            predetermined_lags=(2, None),
            lags=2,
        )
        _assert_matches(r, stata[spec], spec)
        _assert_sample(r, stata[spec], spec)

    def test_endogenous_matches_stata_endogenous(self, abdata, stata):
        """``endogenous(w, lagstruct(1, .))`` == ``endogenous_lags=(3, None)``."""
        spec = "C2_w_endogenous"
        r = _fit(
            abdata,
            x=["l(0/2).k"],
            endogenous=["l(0/1).w"],
            endogenous_lags=(3, None),
            lags=2,
        )
        _assert_matches(r, stata[spec], spec)
        _assert_sample(r, stata[spec], spec)

    def test_class_defaults_are_the_xtabond2_convention(self, abdata):
        """Defaults are absolute lags 1+ (predetermined) / 2+ (endogenous).

        Shifting the window one lag deeper must strictly *reduce* the
        instrument count by the number of equation periods that lose their
        shallowest instrument — a structural check that the class default
        really is where the docstring says it is.
        """
        pre_default = _fit(abdata, predetermined=["w"], lags=1)
        pre_shifted = _fit(
            abdata, predetermined=["w"], predetermined_lags=(2, None), lags=1
        )
        endo_default = _fit(abdata, endogenous=["w"], lags=1)
        assert (
            pre_default.model_info["n_instruments"]
            > pre_shifted.model_info["n_instruments"]
        )
        assert (
            pre_shifted.model_info["n_instruments"]
            == endo_default.model_info["n_instruments"]
        ), "endogenous default (lag 2+) must equal predetermined shifted to 2+"


