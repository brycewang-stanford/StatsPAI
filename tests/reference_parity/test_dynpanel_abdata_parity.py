class TestDiagnostics:
    def test_ar_tests_onestep_robust(self, abdata, stata):
        """e(arm1)/e(arm2) — the tests that decide whether the design holds."""
        spec = "A1_ar1_1step_robust"
        r = _fit(abdata, lags=1, twostep=False, robust=True)
        e = stata[spec]["e"]
        np.testing.assert_allclose(
            [r.model_info["ar1_z"], r.model_info["ar2_z"]],
            [e["arm1"], e["arm2"]],
            rtol=1e-7,
            err_msg=f"[{spec}] Arellano-Bond AR z statistics differ from Stata.",
        )

    def test_ar_tests_onestep_classical(self, abdata, stata):
        spec = "A2_ar1_1step_classic"
        r = _fit(abdata, lags=1, twostep=False, robust=False)
        e = stata[spec]["e"]
        np.testing.assert_allclose(
            [r.model_info["ar1_z"], r.model_info["ar2_z"]],
            [e["arm1"], e["arm2"]],
            rtol=1e-7,
            err_msg=f"[{spec}] classical AR z statistics differ from Stata.",
        )

    def test_sargan_onestep(self, abdata, stata):
        """Stata's e(sargan) after one-step non-robust estimation.

        The statistic is ``g' A1 g / sigma2_hat`` with
        ``sigma2_hat = e'e / (2 (N - k))`` — the ``xtabond`` convention.
        (``xtabond2`` divides by ``2N`` instead, so its ``e(sargan)`` sits a
        factor ``N/(N-k)`` higher; that difference is a convention, not an
        error, and is why ``xtabond`` is the anchor here.)
        """
        spec = "A2_ar1_1step_classic"
        r = _fit(abdata, lags=1, twostep=False, robust=False)
        np.testing.assert_allclose(
            r.model_info["sargan_stat"],
            stata[spec]["e"]["sargan"],
            rtol=1e-9,
            err_msg="Sargan statistic differs from Stata's e(sargan).",
        )
        assert r.model_info["sargan_df"] == 27

    def test_hansen_j_matches_stata_twostep_sargan(self, abdata, stata):
        """After ``twostep``, Stata's e(sargan) *is* the Hansen J.

        Stata reuses the ``e(sargan)`` slot for the two-step statistic
        ``g2' A2 g2``, which is the heteroskedasticity-robust Hansen J.
        StatsPAI keeps the two names distinct, so the comparison is against
        ``hansen_stat``.
        """
        spec = "A5_ar1_2step_conv"
        r = _fit(abdata, lags=1, twostep=True, robust=False)
        np.testing.assert_allclose(
            r.model_info["hansen_stat"],
            stata[spec]["e"]["sargan"],
            rtol=1e-9,
            err_msg="Hansen J differs from Stata's post-twostep e(sargan).",
        )
        assert r.model_info["hansen_df"] == 27


