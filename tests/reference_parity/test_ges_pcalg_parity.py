"""``sp.ges`` against ``pcalg::ges`` (forward + backward phases), CPDAG by CPDAG.

Thirty random linear-Gaussian DAGs (4 to 7 nodes, n in {300, 1000, 3000},
edge density 0.25 to 0.6, random topological order) are generated by
:func:`make_datasets`, written to CSV, and run through
``pcalg::ges(new("GaussL0penObsScore", d), phase = c("forward",
"backward"), iterate = FALSE)``; the essential graphs are in
``_fixtures/ges_pcalg_R.json`` (pcalg 2.7.12, R 4.5;
``_fixtures/_generate_ges_pcalg_R.R``). pcalg is GPL, so it is compared as
a black box only; ``sp.ges`` is written from Chickering (2002).

The earlier DAG-space search with a v-structure-only CPDAG matched 11 of
the 30; the test requires every one, mark for mark.

Regenerate::

    python -c "import sys; sys.path.insert(0, 'tests/reference_parity'); \\
        import test_ges_pcalg_parity as t; t.write_csvs('/tmp/ges')"
    Rscript tests/reference_parity/_fixtures/_generate_ges_pcalg_R.R /tmp/ges
"""

from __future__ import annotations

import io
import json
import pathlib

import numpy as np
import pandas as pd
import pytest

import statspai as sp

_FIX = pathlib.Path(__file__).parent / "_fixtures"


def make_datasets():
    out = {}
    for seed in range(30):
        r = np.random.default_rng(1000 + seed)
        p = int(r.integers(4, 8))
        n = int(r.choice([300, 1000, 3000]))
        dens = r.uniform(0.25, 0.6)
        B = np.zeros((p, p))
        for i in range(p):
            for j in range(i + 1, p):
                if r.uniform() < dens:
                    B[i, j] = r.choice([-1, 1]) * r.uniform(0.4, 1.0)
        perm = r.permutation(p)
        X = np.zeros((n, p))
        for j in range(p):
            X[:, j] = X @ B[:, j] + r.normal(size=n) * r.uniform(0.5, 1.5)
        df = pd.DataFrame(X[:, perm], columns=[f"v{k}" for k in range(p)]).round(10)
        # the bytes R read: a CSV round trip
        buf = io.StringIO()
        df.to_csv(buf, index=False)
        out[f"g{seed:02d}.csv"] = buf.getvalue()
    return out


def write_csvs(directory):  # pragma: no cover - fixture regeneration
    d = pathlib.Path(directory)
    d.mkdir(parents=True, exist_ok=True)
    for name, text in make_datasets().items():
        (d / name).write_text(text, encoding="utf-8")


@pytest.fixture(scope="module")
def reference():
    return json.loads((_FIX / "ges_pcalg_R.json").read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def datasets():
    return make_datasets()


def test_ges_matches_pcalg_on_every_graph(reference, datasets):
    assert set(reference) == set(datasets)
    mismatched = []
    for name, text in sorted(datasets.items()):
        df = pd.read_csv(io.StringIO(text), float_precision="round_trip")
        want = np.asarray(reference[name]["amat"], dtype=int)
        got = sp.ges(df).adjacency
        if not np.array_equal(got, want):
            mismatched.append(name)
    assert mismatched == []


def test_compelled_edge_below_a_collider_is_directed():
    """X -> Z <- Y, Z -> W: Meek's R1 compels Z -> W (the old CPDAG step
    left it undirected)."""
    rng = np.random.default_rng(0)
    n = 2000
    X = rng.normal(size=n)
    Y = rng.normal(size=n)
    Z = 0.8 * X + 0.8 * Y + rng.normal(size=n)
    W = 0.9 * Z + rng.normal(size=n)
    res = sp.ges(pd.DataFrame({"X": X, "Y": Y, "Z": Z, "W": W}))
    assert sorted(res.edges()) == [
        ("X", "Z", "-->"),
        ("Y", "Z", "-->"),
        ("Z", "W", "-->"),
    ]


def test_bic_is_the_score_of_a_dag_in_the_class():
    """Score equivalence: the reported BIC equals the BIC of the generating
    DAG's class computed by hand (chain x -> y -> z, any orientation)."""
    rng = np.random.default_rng(3)
    n = 1500
    x = rng.normal(size=n)
    y = 0.7 * x + rng.normal(size=n)
    z = -0.6 * y + rng.normal(size=n)
    df = pd.DataFrame({"x": x, "y": y, "z": z})
    res = sp.ges(df)
    assert sorted(res.edges()) == [("x", "y", "---"), ("y", "z", "---")]

    def bic(col, parents):
        A = np.column_stack([np.ones(n)] + [df[c].to_numpy() for c in parents])
        beta = np.linalg.lstsq(A, df[col].to_numpy(), rcond=None)[0]
        rss = float(np.sum((df[col].to_numpy() - A @ beta) ** 2))
        return n * np.log(rss / n) + (len(parents) + 1) * np.log(n)

    by_hand = bic("x", []) + bic("y", ["x"]) + bic("z", ["y"])
    assert res.bic == pytest.approx(by_hand, rel=1e-12)
