def _by_case(rows):
    return {c: tuple(r[j] for r in rows) for j, c in enumerate(_JO_CASES)}


JOHANSEN_CV = {
    "maxeig": {0.05: _by_case(_JO_MAX_95), 0.01: _by_case(_JO_MAX_99)},
    "trace": {0.05: _by_case(_JO_TRACE_95), 0.01: _by_case(_JO_TRACE_99)},
}


def mackinnon_cv(case: str, n_series: int, level_pct: int, nobs: float) -> float:
    """MacKinnon (2010) response-surface critical value for sample size nobs."""
    b0, b1, b2, b3 = MACKINNON_2010[case][(int(n_series), int(level_pct))]
    return b0 + b1 / nobs + b2 / nobs**2 + b3 / nobs**3
