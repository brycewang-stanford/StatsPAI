def stock_yogo_critical_values(
    n_endog: int, n_instruments: int
) -> Optional[Dict[str, Any]]:
    """Critical values for ``n_endog`` endogenous regressors and
    ``n_instruments`` excluded instruments.

    Returns ``None`` when the combination is not tabulated. Otherwise a
    dict with up to three entries, each mapping the tolerated level to the
    critical value: ``'bias_2sls'`` (levels 0.05, 0.10, 0.20, 0.30 of the
    OLS bias), ``'size_2sls'`` and ``'size_liml'`` (sizes 0.10, 0.15, 0.20,
    0.25 of a nominal 5% Wald test).
    """
    key = (int(n_endog), int(n_instruments))
    found: Dict[str, Any] = {}
    for name, table, levels in (
        ("bias_2sls", _BIAS, _BIAS_LEVELS),
        ("size_2sls", _SIZE_2SLS, _SIZE_LEVELS),
        ("size_liml", _SIZE_LIML, _SIZE_LEVELS),
    ):
        if key in table:
            found[name] = dict(zip(levels, table[key]))
    return found or None
