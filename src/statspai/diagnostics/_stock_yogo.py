"""Critical values of Stock and Yogo for the weak-instrument test.

The null is that the instruments are weak: that the bias of 2SLS exceeds a
given fraction of the bias of OLS, or that a nominal 5% Wald test has a
size above a given level. It is rejected when the minimum eigenvalue
statistic of Cragg and Donald (the first-stage F with one endogenous
regressor) exceeds the critical value. The statistic and the values assume
homoskedastic errors; with a robust or clustered covariance use
:func:`statspai.effective_f_test`.

Where the numbers come from. They are the values Stata 18 returns in
``r(mineigcv)`` after ``estat firststage``, read off for every number of
endogenous regressors (1 to 3) and of excluded instruments (up to 30) by
running the command; Stata tabulates Stock and Yogo (2005). The combinations
missing here are missing there: the relative-bias values need at least two
more instruments than endogenous regressors, and the size values are given
for one and two endogenous regressors.

Keys are ``(endogenous regressors, excluded instruments)``.

References
----------
[@stock2005testing]
"""

